package org.proanima.shelter.repository

import com.zaxxer.hikari.HikariConfig
import com.zaxxer.hikari.HikariDataSource
import java.net.URI
import java.net.URISyntaxException
import java.net.URLDecoder
import java.sql.Connection
import javax.sql.DataSource

class DatabaseConfig(val jdbcUrl: String, val username: String?, val password: String?)

private const val DEFAULT_POSTGRES_PORT = 5432

// Neon (and most hosts) hand out a connection string like
// postgresql://user:password@host/dbname?sslmode=require, while the JDBC driver wants the credentials apart
// from the URL. A string that already starts with "jdbc:" is passed through (that is how tests point at H2).
// Error messages never include the string itself: it contains the password.
fun parseDatabaseUrl(url: String): DatabaseConfig {
    if (url.startsWith("jdbc:")) {
        return DatabaseConfig(url, null, null)
    }
    // A value copied from a .env file often keeps its quotes: DATABASE_URL="postgresql://...".
    val uri = try {
        URI(url.trim().removeSurrounding("\"").removeSurrounding("'"))
    } catch (e: URISyntaxException) {
        throw IllegalArgumentException("DATABASE_URL is not a valid URL (${e.reason})")
    }
    require(uri.scheme == "postgresql" || uri.scheme == "postgres") {
        "DATABASE_URL must start with postgresql://"
    }
    val host = uri.host
    require(!host.isNullOrBlank()) { "DATABASE_URL has no host" }
    val database = uri.rawPath.orEmpty().removePrefix("/")
    require(database.isNotBlank()) { "DATABASE_URL has no database name" }

    val userInfo = uri.rawUserInfo
    val username = userInfo?.substringBefore(':')?.let(::percentDecode)?.ifBlank { null }
    val password = userInfo?.takeIf { ':' in it }?.substringAfter(':')?.let(::percentDecode)

    // pgjdbc has no use for channel_binding; everything else (sslmode, ...) goes through unchanged.
    val query = uri.rawQuery.orEmpty().split('&').filter { it.isNotBlank() && !it.startsWith("channel_binding=") }
    val port = if (uri.port == -1) DEFAULT_POSTGRES_PORT else uri.port
    val jdbcUrl = "jdbc:postgresql://$host:$port/$database" + if (query.isEmpty()) "" else "?" + query.joinToString("&")
    return DatabaseConfig(jdbcUrl, username, password)
}

// A plus sign in a password is a plus sign, not a space, so only %XX sequences are decoded.
private fun percentDecode(value: String): String = URLDecoder.decode(value.replace("+", "%2B"), Charsets.UTF_8)

// Neon puts an idle database to sleep after about five minutes and drops its connections, so the pool keeps
// no idle connections for long and renews them before that. No keep-alive pings: they would keep the
// database awake all month and eat the free hours.
fun createDataSource(config: DatabaseConfig): HikariDataSource = HikariDataSource(
    HikariConfig().apply {
        jdbcUrl = config.jdbcUrl
        config.username?.let { username = it }
        config.password?.let { password = it }
        poolName = "shelter"
        maximumPoolSize = 3
        minimumIdle = 0
        idleTimeout = 60_000
        maxLifetime = 240_000
        // A sleeping database needs a few seconds to wake up.
        connectionTimeout = 10_000
        initializationFailTimeout = 30_000
    }
)

// Every statement here is plain SQL that PostgreSQL and H2 both accept. The cat and dog documents are
// stored as text: they are always read and written whole through the serializer, so jsonb would add nothing.
private val SCHEMA = listOf(
    """
    CREATE TABLE IF NOT EXISTS cats (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS dogs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS photos (
        name VARCHAR(255) PRIMARY KEY,
        content_type VARCHAR(100) NOT NULL,
        data BYTEA NOT NULL,
        sha256 VARCHAR(64) NOT NULL,
        created_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS app_meta (
        meta_key VARCHAR(100) PRIMARY KEY,
        meta_value TEXT NOT NULL
    )
    """,
    // The sections made in the admin panel and the entries of all of them, as documents like the cats and the dogs.
    """
    CREATE TABLE IF NOT EXISTS sections (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS section_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    // The menu tree saved in the admin panel: one row (id 1), one document. No row means the menu was never saved.
    """
    CREATE TABLE IF NOT EXISTS site_menu (
        id INTEGER PRIMARY KEY,
        data TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL
    )
    """,
    // The texts of the site's pages that were edited in the admin panel; a key with no row here has the text that
    // comes with the code. lang is "ru", "en", "sr", or "all" for a value that is the same in every language.
    """
    CREATE TABLE IF NOT EXISTS site_content (
        content_key VARCHAR(120) NOT NULL,
        lang VARCHAR(8) NOT NULL,
        body TEXT NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
        PRIMARY KEY (content_key, lang)
    )
    """
)

fun createSchema(dataSource: DataSource) {
    dataSource.inTransaction { connection ->
        connection.createStatement().use { statement ->
            SCHEMA.forEach { statement.execute(it.trimIndent()) }
        }
    }
}

// Commits when the block returns, rolls everything back when it throws.
internal fun <T> DataSource.inTransaction(block: (Connection) -> T): T = connection.use { connection ->
    connection.autoCommit = false
    try {
        block(connection).also { connection.commit() }
    } catch (e: Throwable) {
        connection.rollback()
        throw e
    }
}
